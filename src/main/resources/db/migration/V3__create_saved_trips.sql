CREATE TABLE travel_trips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    source VARCHAR(100) NOT NULL,
    destination VARCHAR(100) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    travelers INTEGER NOT NULL CHECK (travelers BETWEEN 1 AND 20),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_travel_trips_user FOREIGN KEY (user_id)
        REFERENCES app_users (id) ON DELETE CASCADE
);

CREATE INDEX ix_travel_trips_user_created_at ON travel_trips (user_id, created_at DESC);
